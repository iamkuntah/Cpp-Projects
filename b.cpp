#include <iostream>
#include <cmath>

using namespace std;

int main() {
  int a = 2;
  double b = 4;


 cout<< sqrt(36)<<endl;// gives out the square root.
 cout<< ceil(4.2)<<endl;// automatically rounds the number up no matter the decimal number.
 cout<< floor(4.9)<<endl;// rounds the number down no matter the decimal number.
 cout<< round(4.6)<<endl;// rounds off the number normally.
 cout<< fmax(a , b)<<endl; // returns the bigger value between a and b.
 cout<< fmin(a , b)<<endl; // returns the smallest value between the two.

 return 0;
 }
